    private fun normalize(value: String): String =
        Normalizer.normalize(value.trim(), Normalizer.Form.NFD)
            .replace("\\p{M}+".toRegex(), "")
            .lowercase(Locale.ROOT)

    /** Forma espiritual existe antes da compra dos Encantos. Minúscula/Lendária é válida
     * como forma espiritual; os Encantos apropriados são exigidos apenas para assumi-la.
     */
    fun selecionarInicial(random: Random = Random.Default): Animal =
        (small + medium + large).random(random)

    /** Catálogo completo para auditorias de coerência visual; não altera a seleção mecânica. */
    internal fun todasFormas(): List<Animal> = small + medium + large

    fun animalPorNome(nome: String): Animal? {
        val alvo = normalize(nome)
        return (small + medium + large).firstOrNull {
            normalize(it.portuguese) == alvo || normalize(it.english) == alvo
        }
    }

    fun selecionarSecundaria(principal: Animal, random: Random = Random.Default): Animal =
        (small + medium + large).filterNot { it.portuguese == principal.portuguese }.random(random)

    fun selecionar(charms: List<EncantoEncontro>, random: Random = Random.Default): Animal {
        val nomes = charms.map { normalize(it.nome) }.toSet()
        return when {
            normalize("Forma Bestial Imponente") in nomes -> large.random(random)
            normalize("Forma do Gafanhoto Esmeralda") in nomes -> small.random(random)
            else -> medium.random(random)
        }
    }

    fun exibir(animal: Animal, locale: Locale = Locale.getDefault()): String =
        if (locale.language.equals("en", ignoreCase = true)) animal.english else animal.portuguese
